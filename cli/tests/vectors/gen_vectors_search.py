#!/usr/bin/env python3
"""
gen_vectors_search.py — NGUỒN SỰ THẬT cho test byte-exact của nhánh SEARCH
(protocol/search/search_api). Xuất tests/vectors/generated_vectors_search.h
(namespace `vsearch`, committed). Xem AGENTS.md §1.

Ground-truth = ../analytics/app/search_web_client.py (build_search_body /
build_suggest_body / parse_search_page / parse_suggest), nạp response CAPTURE
THẬT đã rút gọn trong tests/fixtures/search*_sample.json.

Tách riêng khỏi gen_vectors.py (drift capability) — chỉ import module search.

Chạy:  python3 tests/vectors/gen_vectors_search.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent            # tests/vectors
TESTS = HERE.parent                               # tests
APP_DIR = TESTS.parent.parent / "analytics" / "app"
sys.path.insert(0, str(APP_DIR))

import search_web_client as sw  # noqa: E402

UUID = "11111111-2222-4333-8444-555555555555"     # uuid cố định cho vector tất định

SEARCH_CASES = [
    # name, query, kwargs
    ("simple", "无上神帝", {}),
    ("page2", "庆余年", {"page": 1, "pre_qid": "QID-abc_123-x", "trans_info": "ti=1&x=2"}),
    ("escape", 'a"b\\c/d 😀', {"page_size": 30, "filter_value": "150", "search_datakey": "k=v"}),
    ("empty", "", {"query_from": 101}),
]
STRIP_CASES = [
    "<em>无上</em>神帝", "a<>b", "a<b", "<<a>>", "x<br/>y", "<a href=\"u\">t</a>", "无<em>", "</>", "",
]
SUGGEST_CASES = [
    ("simple", "无上神帝", 10),
    ("small", "avatar", 3),
]


def raw(s: str) -> str:
    assert ')vec"' not in s
    return 'R"vec(' + s + ')vec"'


def render_page(page: dict) -> str:
    out = [f"qid={page['qid']}", f"total={page['total_num']}", f"items={len(page['items'])}"]
    for it in page["items"]:
        out.append("item|" + "|".join([
            str(it["data_type"]), it["id"], it["md"], it["type_name"], it["title"],
            it["sub_title"], str(it["year"]), it["area"], ",".join(it["languages"]),
            ",".join(it["actors"]), ",".join(it["directors"]), ",".join(it["badges"]),
            ",".join(it["tags"]), str(it["total_episode"]), str(len(it["episodes"])),
        ]))
        for ep in it["episodes"]:
            out.append("ep|" + "|".join([ep["id"], ep["title"], ep["url"], ";".join(ep["marks"])]))
    return "\n".join(out) + "\n"


def render_suggest(items: list[dict]) -> str:
    out = [f"count={len(items)}"]
    for it in items:
        out.append("sug|" + "|".join([str(it["data_type"]), it["id"], it["md"], it["text"],
                                      it["image_url"]]))
    return "\n".join(out) + "\n"


def main() -> int:
    search_fixture = json.loads((TESTS / "fixtures" / "search_response.sample.json").read_text("utf-8"))
    suggest_fixture = json.loads(
        (TESTS / "fixtures" / "search_suggest_response.sample.json").read_text("utf-8"))

    lines = [
        "// GENERATED by tests/vectors/gen_vectors_search.py — KHÔNG sửa tay.",
        "// Ground-truth: ../analytics/app/search_web_client.py. Xem AGENTS.md §1.",
        "#pragma once",
        "",
        "namespace vsearch {",
        "",
        f'constexpr const char* kUuid = "{UUID}";',
        "",
        "struct SearchBodyCase {",
        "  const char* name;",
        "  const char* query;",
        "  int page;",
        "  int page_size;",
        "  const char* filter_value;",
        "  const char* pre_qid;",
        "  const char* trans_info;",
        "  const char* search_datakey;",
        "  int query_from;",
        "  const char* expected;",
        "};",
        "inline const SearchBodyCase kSearchBodies[] = {",
    ]
    defaults = {"page": 0, "page_size": 15, "filter_value": "", "pre_qid": "",
                "trans_info": "", "search_datakey": "", "query_from": 0}
    for name, query, kw in SEARCH_CASES:
        a = {**defaults, **kw}
        body = sw.dump_body(sw.build_search_body(query, uuid_value=UUID, **a))
        lines.append(
            f'    {{"{name}", {raw(query)}, {a["page"]}, {a["page_size"]}, {raw(a["filter_value"])}, '
            f'{raw(a["pre_qid"])}, {raw(a["trans_info"])}, {raw(a["search_datakey"])}, '
            f'{a["query_from"]}, {raw(body)}}},')
    lines += ["};", "", "struct SuggestBodyCase {", "  const char* name;", "  const char* query;",
              "  int page_size;", "  const char* expected;", "};",
              "inline const SuggestBodyCase kSuggestBodies[] = {"]
    for name, query, size in SUGGEST_CASES:
        body = sw.dump_body(sw.build_suggest_body(query, page_size=size))
        lines.append(f'    {{"{name}", {raw(query)}, {size}, {raw(body)}}},')
    lines += ["};", "", "struct StripCase {", "  const char* input;", "  const char* expected;", "};",
              "inline const StripCase kStripCases[] = {"]
    for text in STRIP_CASES:
        lines.append(f"    {{{raw(text)}, {raw(sw.plain(text))}}},")
    lines += ["};", ""]

    page = sw.parse_search_page(search_fixture["data"])
    sug = sw.parse_suggest(suggest_fixture["data"])
    lines.append(f"inline const char* const kSearchPageExpected = {raw(render_page(page))};")
    lines.append(f"inline const char* const kSuggestExpected = {raw(render_suggest(sug))};")
    lines += ["", "}  // namespace vsearch", ""]

    out = HERE / "generated_vectors_search.h"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes): "
          f"{len(SEARCH_CASES)} search bodies, {len(SUGGEST_CASES)} suggest bodies, "
          f"{len(page['items'])} items, {len(sug)} suggestions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
